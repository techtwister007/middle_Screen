/** Translate English UI text. {placeholders} are filled from vars; unknown text stays English. */
export function translate(lang: Lang, en: string, vars?: Record<string, string | number>) {
  const row = lang === "en" ? undefined : DICT[en];
  let s = row ? row[lang === "hi" ? 0 : 1] : en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
