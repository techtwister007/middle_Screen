export type DictKey = keyof typeof dict
export type Vars = Record<string, string | number | null | undefined>

export const asLang = (lang: string | undefined | null): Lang => (lang === 'hi' || lang === 'gu' ? lang : 'en')

export const t = (lang: string | undefined | null, key: DictKey, vars?: Vars): string => {
  const entry = dict[key] as Entry | undefined
  const raw = entry ? entry[asLang(lang)] || entry.en : String(key)
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (vars[name] === undefined || vars[name] === null ? m : String(vars[name])))
}

/** For dynamic keys built from data (occasions, categories, statuses). Falls back to `fallback` when missing. */
export const tOr = (lang: string | undefined | null, key: string, fallback: string, vars?: Vars): string =>
  key in dict ? t(lang, key as DictKey, vars) : fallback

/** Bind a language once: `const tr = translator(lang); tr('book')`. */
export const translator = (lang: string | undefined | null) => {
  const l = asLang(lang)
  const tr = (key: DictKey, vars?: Vars) => t(l, key, vars)
  tr.or = (key: string, fallback: string, vars?: Vars) => tOr(l, key, fallback, vars)
  tr.lang = l
  return tr
}
export type Translator = ReturnType<typeof translator>

/** "1 h 30 min" / "1 घं 30 मि" / "1 કલાક 30 મિનિટ" */
export const formatDurationIn = (lang: string | undefined | null, minutes?: number | null) => {
  if (!minutes) return ''
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  const H = t(lang, 'hours')
  const M = t(lang, 'minutes')
  if (h && m) return `${h} ${H} ${m} ${M}`
  if (h) return `${h} ${H}`
  return `${m} ${M}`
}

